/// 一輪輪詢走到哪裡收尾。
///
/// 三態分開表達的理由：`complete` 與 `truncated` 都是正常運作，差別在**站台還有沒有沒讀到的頁**；
/// 把兩者壓成一個布林值，呼叫端就沒有辦法區分「沒事發生」與「事情多到讀不完」。
/// `stalled` 更是必須浮上檯面——它是會自己重複下去的狀態。
public enum PollCompletion: Sendable, Equatable {

    /// 走到最後一頁——站台沒有再多的頁了。
    ///
    /// ⚠ **不等於「游標之後的資料全在 `elements` 裡」。** 翻頁期間集合被改動會讓某一筆跨過已讀邊界
    /// （見 `ProjectResourcePoller`），走完最後一頁也補不回來；那一筆仍在新游標之上、下一輪會讀到，
    /// 但**本輪的 `elements` 不是完整快照**。拿它當「游標之後的全集」去做對帳、判定關閉、
    /// 或清掉沒出現在其中的東西，會對著一個少了一筆的集合動手。
    case complete

    /// 撞到翻頁預算、站台還有下一頁。
    ///
    /// ⚠ **它只代表「還有頁沒讀」，不代表游標動了。** 第一頁的最新資源若寫在當前這一整秒內，
    /// 取整後推不動游標，本輪照樣是 `truncated`。要知道有沒有前進，比對回傳的 `cursor` 與傳入值，
    /// 別從這個 case 推論——照這個 case 推論而不自己比對的呼叫端，會在原地空轉而毫無察覺。
    ///
    /// 不記「下一頁頁碼」是因為它下一輪就失效了：游標一動，站台的分頁邊界整個重算，
    /// 舊頁碼指向的位置與這一輪不是同一批資料。續讀一律從新游標的第一頁開始。
    case truncated

    /// 游標推不動，而且原因出在第一頁本身——不是時鐘。
    ///
    /// 只收兩種形狀，兩種都由「游標只採信第一頁」這條規則直接推出、與時鐘無關：
    ///
    /// 1. **同一秒的資源多到塞滿第一頁**——最典型的是一次交易批次改動大量資源、共用同一個
    ///    `updated_at`。第一頁整頁落在游標那一秒內，游標無處可去，而且**沒有安全的跨越方式**
    ///    （理由見 `ProjectResourcePoller`）。翻頁參數幫不上忙；要往前得由握有去重狀態的呼叫端決定。
    ///    **資料一筆都沒丟**，只是讀不到更新的。
    ///    ⚠ 每輪讀到的**未必是同一批**：時間戳完全相同的資源在不同次請求之間順序未定，
    ///    同一個平手群可能每輪回不同的子集合。呼叫端不可因為「上輪處理過了」就跳過本輪的內容。
    /// 2. **第一頁是空的、集合卻還有後續**——站台不該這樣回。此時沒有任何可採信的第一頁證據，
    ///    游標因此不動。這是站台或中間層的異常，往站台端查。
    ///    ⚠ 這一條與第 1 條的把握程度不同：第 1 條由規則本身推出、必然重複；這一條只說明
    ///    **本輪沒有可採信的第一頁證據**。若那個空回應是快取或代理偶發送出的，下一輪就會恢復正常。
    ///
    /// ⚠ **與時鐘有關的推不動一律不在此列。** 上限落後資料、沒有 `Date` 標頭、兩個時鐘對不上——
    /// 這些都可能下一秒就自己好，而本輪看不出來；報成「不會自己好」就是誤報，
    /// 而這個狀態一旦開始誤報就沒有人會再認真看它。時鐘的狀況由
    /// `ResourcePollResult.capIsTrustworthy` 表達，「跨輪都沒動」則由保存游標的呼叫端自己看得出來。
    ///
    /// ⚠ 反過來也不成立：**回報 `complete` 不保證有進展**。同一秒的資源塞滿第一頁、而且整個集合裡
    /// 沒有更新的資源時，本輪讀完了全部、游標卻推不動，於是每輪重發同一批而回報 `complete`。
    /// 那個狀態不漏資料，也會在出現更新的資源時自己轉成上面第 1 種。
    case stalled
}

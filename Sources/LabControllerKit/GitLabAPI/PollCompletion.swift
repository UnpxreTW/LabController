/// 一輪輪詢走到哪裡收尾。
///
/// 三態分開表達的理由：`complete` 與 `truncated` 都是正常運作，但**只有 `complete` 代表
/// 「游標之後的資料本輪都看過了」**；把兩者壓成一個布林值，呼叫端就沒有辦法區分
/// 「沒事發生」與「事情多到讀不完」。`stalled` 更是必須浮上檯面——它是會自己重複下去的狀態。
public enum PollCompletion: Sendable, Equatable {

    /// 走到最後一頁。游標之後的資料本輪全數讀入。
    case complete

    /// 撞到翻頁預算、站台還有下一頁；游標已前進，下一輪從新游標接著讀。
    ///
    /// 不記「下一頁頁碼」是因為它下一輪就失效了：游標一動，站台的分頁邊界整個重算，
    /// 舊頁碼指向的位置與這一輪不是同一批資料。續讀一律從新游標的第一頁開始。
    case truncated

    /// 游標推不動，而且下一輪還會是同一個狀態。
    ///
    /// 每一輪各自看起來都「成功」了，實際上原地重複。四種成因，處置各不相同：
    ///
    /// 1. **同一秒的資源多到塞滿第一頁**——最典型的是一次交易批次改動大量資源、共用同一個
    ///    `updated_at`。游標無處可去，而且**沒有安全的跨越方式**（理由見 `ProjectResourcePoller`）。
    ///    翻頁參數幫不上忙；要往前得由握有去重狀態的呼叫端決定。**資料一筆都沒丟**，只是讀不到更新的。
    /// 2. **第一頁是空的、卻還有下一頁**——站台不該這樣回。此時沒有任何可採信的第一頁證據，
    ///    游標因此不動。這是站台或中間層的異常，往站台端查。
    /// 3. **回應沒有可解析的 `Date` 標頭，而本機時鐘落後站台**——上限只好由本機時鐘往前扣容差推得，
    ///    於是早於所有資料、一路壓住游標。查為什麼回應沒有 `Date` 標頭，或校正本機時鐘與容差。
    /// 4. **有 `Date` 標頭，但它與本機時鐘差距超過容差**——前端快取或時鐘停住的節點會發出固定、過期
    ///    甚至指向未來的 `Date`。此時回應**有**標頭、本機時鐘也**可能完全正常**，該查的是發出那個標頭的
    ///    節點（快取層、反向代理），不是本機。
    ///
    /// 四者都不會自己好。
    ///
    /// ⚠ **`Date` 標頭與本機時鐘對得上時被壓住，不算在內。** 那個標頭只有整秒精度、又扣掉了來回耗時，
    /// 因此系統性地落後真實時刻約一秒：最近一秒內的異動本輪推不動、下一輪就推得動了。
    /// 那是暫時的、會自己好，報成 `stalled` 只會讓完全正常的站台每有一筆剛發生的異動就誤報一次——
    /// 而這個狀態一旦開始誤報，就沒有人會再認真看它。
    ///
    /// ⚠ 反過來也不成立：**回報 `complete` 不保證有進展**。同一秒的資源塞滿第一頁、而且整個集合裡
    /// 沒有更新的資源時，本輪讀完了全部、游標卻推不動，於是每輪重發同一批而回報 `complete`。
    /// 那個狀態不漏資料，也會在出現更新的資源時自己轉成上面第 1 種。
    case stalled
}

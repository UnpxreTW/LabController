/// 一輪輪詢走到哪裡收尾。
///
/// 三態分開表達的理由：`complete` 與 `truncated` 都是正常運作，但**只有 `complete` 代表
/// 「游標之後的資料本輪都看過了」**；把兩者壓成一個布林值，呼叫端就沒有辦法區分
/// 「沒事發生」與「事情多到讀不完」。`stalled` 更是必須浮上檯面——它是會自己重複下去的狀態。
public enum PollCompletion: Sendable, Equatable {

    /// 走到最後一頁。游標之後的資料本輪全數讀入。
    case complete

    /// 撞到翻頁預算、站台還有下一頁；游標已前進，下一輪從新游標接著讀。
    ///
    /// 不記「下一頁頁碼」是因為它下一輪就失效了：游標一動，站台的分頁邊界整個重算，
    /// 舊頁碼指向的位置與這一輪不是同一批資料。續讀一律從新游標的第一頁開始。
    case truncated

    /// 有東西可以推進游標，游標卻一步都沒動。
    ///
    /// 下一輪會讀到一模一樣的內容、再次不動，如此反覆，而每一輪各自看起來都「成功」了。
    /// 三種成因，處置各不相同：
    ///
    /// 1. **同一秒的資源多到塞滿第一頁**——最典型的是一次交易批次改動大量資源、共用同一個
    ///    `updated_at`。游標無處可去，而且**沒有安全的跨越方式**（理由見 `ProjectResourcePoller`）。
    ///    翻頁參數幫不上忙；要往前得由握有去重狀態的呼叫端決定。**資料一筆都沒丟**，只是讀不到更新的。
    /// 2. **游標被時鐘上限壓住**——取不到站台時鐘而本機時鐘落後站台時，上限會早於所有資料，
    ///    推進值一律被壓回原位。解法在時鐘：查為什麼回應沒有 `Date` 標頭，或校正本機時鐘與容差。
    /// 3. **第一頁是空的、卻還有下一頁**——站台不該這樣回。此時沒有任何可採信的第一頁證據，
    ///    游標因此不動。這是站台或中間層的異常，往站台端查。
    ///
    /// 三者都不會自己好。
    ///
    /// ⚠ 反過來不成立：**回報 `complete` 不保證有進展**。同一秒的資源塞滿第一頁、而且整個集合裡
    /// 沒有更新的資源時，本輪讀完了全部、游標卻推不動，於是每輪重發同一批而回報 `complete`。
    /// 那個狀態不漏資料，也會在出現更新的資源時自己轉成上面第 1 種。
    case stalled
}
